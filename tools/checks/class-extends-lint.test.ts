const probes = [
  ...cases.map(([statement, expected, setup = []], index) => ({
    cases: [[statement, expected]] as Cases,
    header: [...HEADER, ...setup],
    kind: `class-extends-${index}`,
  })),
  {
    cases: globalsCases,
    header: [
      "class Base {}",
      "Object.assign(globalThis, { Leak: Base });",
      "const globalAlias = globalThis;",
    ],
    kind: "class-extends-globals",
  },
  {
    cases: reachedGlobalCases,
    header: ["class Base {}", 'Function("return this")().Error = Base;'],
    kind: "class-extends-function",
  },
  {
    cases: builtinCases,
    header: ["class Base {}", "SyntaxError = Base as never;"],
    kind: "class-extends-builtin",
  },
].map((probe) => Object.assign(probe, { path: probePath("apps/coding-agent/src", probe.kind) }));

const sourceOf = (header: readonly string[], probeCases: Cases): string =>
  [...header, ...probeCases.map(([statement]) => statement)].join("\n");

it("flags coding-agent classes whose superclass is not syntactically a class from outside the package", () =>
  lintProbes(
    Object.fromEntries(
      probes.map(({ cases: probeCases, header, path }) => [path, sourceOf(header, probeCases)]),
    ),
  ).then((report) => {
    expect(
      probes.flatMap(({ cases: probeCases, header, path }) =>
        probeCases.map(([statement], index) => ({
          codes: codesOnLine(report, path, header.length + index + 1, LOCAL_EXTENDS),
          statement,
        })),
      ),
    ).toEqual(
      probes.flatMap(({ cases: probeCases }) =>
        probeCases.map(([statement, expected]) => ({
          codes: expected === undefined ? [] : [expected],
          statement,
        })),
      ),
    );
    return undefined;
  }));
